export function initEsma(root) {
  root.innerHTML = `
    <div class="esma-arama">
      <input type="search" id="esma-input" placeholder="İsim veya anlam ara…"
             aria-label="Esmaü'l-Hüsna içinde ara" />
    </div>
    <ul class="esma-list" id="esma-list"></ul>
  `;

  const list = root.querySelector("#esma-list");
  const input = root.querySelector("#esma-input");

  function render(filtre = "") {
    const f = filtre.toLocaleLowerCase("tr");
    list.innerHTML = ESMA.map(([ad, arapca, anlam], i) => {
      if (f && !ad.toLocaleLowerCase("tr").includes(f) && !anlam.toLocaleLowerCase("tr").includes(f)) {
        return "";
      }
      return `<li class="esma-row">
        <span class="esma-no">${i + 1}</span>
        <div class="esma-orta">
          <span class="esma-ad">${ad}</span>
          <span class="esma-anlam">${anlam}</span>
        </div>
        <span class="esma-arapca">${arapca}</span>
      </li>`;
    }).join("") || `<li class="esma-bos">Sonuç bulunamadı</li>`;
  }

  input.addEventListener("input", () => render(input.value.trim()));
  render();
}
